var currentLang = "en";

// Gives back one text in the language that is active now
function getText(key) {
    return texts[currentLang][key];
}

/* Number check */

// Gives back an empty string if the number is fine, or the error message if it is not
function checkNumber(value, min, max) {
    if (value.trim() === "") {
        return getText("err.empty");
    }

    var number = Number(value);

    if (isNaN(number)) {
        return getText("err.number");
    }

    if (!Number.isInteger(number)) {
        return getText("err.integer");
    }

    if (number < min || number > max) {
        return getText("err.range").replace("{min}", min).replace("{max}", max);
    }

    return "";
}

function showError(errorBox, message) {
    errorBox.textContent = message; // textContent error never inserts HTML
    errorBox.hidden = false;
}

function hideError(errorBox) {
    errorBox.textContent = "";
    errorBox.hidden = true;
}

/* Challenge 1 factorial */

var factorialForm = document.getElementById("factorial-form");
var factorialInput = document.getElementById("factorial-input");
var factorialOutput = document.getElementById("factorial-output");
var factorialHint = document.getElementById("factorial-hint");
var factorialError = document.getElementById("factorial-error");

// Logic, 6! ... gives 6 * 5 * 4 * 3 * 2 * 1 = 720
function factorial(number) {
    var result = 1;

    for (var i = 2; i <= number; i++) {
        result = result * i;
    }

    return result;
}

function calculateFactorial(event) {
    event.preventDefault();

    var message = checkNumber(factorialInput.value, 1, 18);

    if (message !== "") {
        showError(factorialError, message);
        factorialOutput.textContent = "—";
        factorialHint.textContent = "";
        return;
    }

    hideError(factorialError);

    var number = Number(factorialInput.value);
    var result = factorial(number);

    factorialOutput.textContent = result;
    factorialHint.textContent = number + "! = " + result;
}

if (factorialForm) {
    factorialForm.addEventListener("submit", calculateFactorial);
}

/* Challenge 2 SKIM loop  */

var loopForm = document.getElementById("loop-form");
var loopInput = document.getElementById("loop-input");
var loopConsole = document.getElementById("loop-console");
var loopError = document.getElementById("loop-error");

function runLoop(event) {
    event.preventDefault();

    var message = checkNumber(loopInput.value, 1, 1000);

    if (message !== "") {
        showError(loopError, message);
        return;
    }

    hideError(loopError);

    var number = Number(loopInput.value);

    loopConsole.innerHTML = ""; // clean the previous result

    for (var i = 1; i <= number; i++) {
        var text = i;

        if (i % 3 === 0 && i % 5 === 0) {
            text = "SKIM is a great place to work!!";
        } else if (i % 3 === 0) {
            text = "SKIM";
        } else if (i % 5 === 0) {
            text = "is a great place to work!!";
        }

        console.log(text);

        // the counter on the left and the text on the right
        var line = document.createElement("p");

        var counter = document.createElement("span");
        counter.className = "idx";
        counter.textContent = i;

        var value = document.createElement("span");
        value.textContent = text;

        line.appendChild(counter);
        line.appendChild(value);
        loopConsole.appendChild(line);
    }
}

if (loopForm) {
    loopForm.addEventListener("submit", runLoop);
}

/* Language selector */

var langList = document.getElementById("lang-list");
var langCode = document.getElementById("lang-code");
var languageSelect = document.querySelector(".language-select");
var languageCurrent = document.querySelector(".language-select-current");

function showLanguageList() {
    langList.innerHTML = "";

    for (var i = 0; i < languages.length; i++) {
        // the language that is active is not shown in the list
        if (languages[i].code !== currentLang) {
            var button = document.createElement("button");
            button.type = "button";
            button.textContent = languages[i].name;
            button.setAttribute("data-lang", languages[i].code);
            button.addEventListener("click", clickLanguage);

            var item = document.createElement("li");
            item.appendChild(button);
            langList.appendChild(item);
        }
    }
}

function clickLanguage() {
    changeLanguage(this.getAttribute("data-lang"));
    languageSelect.classList.remove("open");
}

function changeLanguage(lang) {
    currentLang = lang;
    document.documentElement.lang = lang;
    langCode.textContent = lang.slice(0, 2);

    // Translates every element that has data-i18n
    var elements = document.querySelectorAll("[data-i18n]");

    for (var i = 0; i < elements.length; i++) {
        elements[i].textContent = getText(elements[i].getAttribute("data-i18n"));
    }

    // The start, back and next buttons keep the language always
    var links = document.querySelectorAll("a[data-page]");

    for (var j = 0; j < links.length; j++) {
        links[j].href = links[j].getAttribute("data-page") + "?lang=" + lang;
    }

    // Old error messages are in the old language
    if (factorialError) {
        hideError(factorialError);
    }

    if (loopError) {
        hideError(loopError);
    }

    showLanguageList();
}

